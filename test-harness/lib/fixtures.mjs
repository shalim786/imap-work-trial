export function cloneFixture(item) {
  return {
    ...item,
    labels: [...item.labels],
    to: [...item.to],
    raw: Buffer.from(item.raw),
  };
}

export function rawSha256(raw) {
  return createHash("sha256").update(raw).digest("hex");
}
