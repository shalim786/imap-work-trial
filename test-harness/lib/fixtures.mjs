import { createHash } from "node:crypto";

function rawMessage(lines) {
  return Buffer.from(`${lines.join("\r\n")}\r\n`, "utf8");
}

function fixture({
  id,
  threadId,
  labels,
  timestamp,
  from,
  to,
  subject,
  preview,
  text,
  raw,
}) {
  return Object.freeze({
    id,
    threadId,
    labels: Object.freeze([...labels]),
    timestamp,
    from,
    to: Object.freeze([...to]),
    subject,
    preview,
    text,
    raw,
  });
}

